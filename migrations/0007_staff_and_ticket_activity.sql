create table if not exists support.staff_members (
    id bigint generated by default as identity primary key,
    telegram_user_id bigint unique,
    telegram_username text not null,
    display_name text not null,
    role text not null check (role in ('admin', 'support')),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint staff_members_username_normalized check (telegram_username = lower(telegram_username))
);
create unique index if not exists staff_members_username_uidx
    on support.staff_members (telegram_username);

alter table support.tickets add column if not exists title text;
alter table support.tickets add column if not exists last_message_at timestamptz;
update support.tickets
set title = coalesce(title, category || ' — ' || left(regexp_replace(description, '\\s+', ' ', 'g'), 110)),
    last_message_at = coalesce(last_message_at, (select max(sent_at) from support.message_history h where h.ticket_id = tickets.id), created_at);
alter table support.tickets alter column title set not null;
alter table support.tickets alter column last_message_at set not null;
create index if not exists tickets_state_last_message_idx
    on support.tickets (state, last_message_at desc);

create table if not exists support.ticket_assignments (
    id bigint generated by default as identity primary key,
    ticket_id bigint not null references support.tickets (id) on delete cascade,
    staff_telegram_user_id bigint not null,
    assigned_by_telegram_user_id bigint,
    assigned_at timestamptz not null,
    ended_at timestamptz
);
create index if not exists ticket_assignments_staff_ticket_idx
    on support.ticket_assignments (staff_telegram_user_id, ticket_id);
